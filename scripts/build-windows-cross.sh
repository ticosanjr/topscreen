#!/usr/bin/env bash
#
# Cross-builds the Windows plugin DLL from Linux (stopgap for when the CI
# Windows runner is unavailable).
#
#   scripts/build-windows-cross.sh [--work DIR] [--keep]
#
# What it does: downloads a portable LLVM-MinGW (UCRT) toolchain, the OBS
# headers + runtime for the pinned version, generates the libobs import library
# from obs.dll, compiles every plugin source except the Qt dock and writes
# build/topscreen.dll (then `scripts/package.sh` packs it).
#
# Trade-off: the Qt dock is NOT compiled in this mode (Qt for MinGW is a
# different build than the one OBS ships). Use the CI release build when it is
# available for the full feature set.
#
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${TOPSCREEN_WINDOWS_WORK:-${TMPDIR:-/tmp}/topscreen-win-cross}"
OBS_VERSION="31.1.1"
LLVM_MINGW="20261006"

while [ $# -gt 0 ]; do
	case "$1" in
	--work) WORK="$2"; shift 2 ;;
	-h | --help) sed -n '2,16p' "$0"; exit 0 ;;
	*) echo "unknown option: $1"; exit 2 ;;
	esac
done

VER=$(grep -E '^project\(TopScreen VERSION' "$ROOT/CMakeLists.txt" | grep -oE '[0-9]+\.[0-9]+\.[0-9]+')
HOST_ARCH="$(uname -m)"
case "$HOST_ARCH" in
x86_64) HOST=x86_64 ;;
aarch64 | arm64) HOST=aarch64 ;;
*) echo "unsupported host: $HOST_ARCH"; exit 1 ;;
esac

mkdir -p "$WORK"
cd "$WORK"

toolchain_bin() {
	local dir
	dir=$(ls -d "$WORK"/llvm-mingw-*-ucrt-ubuntu-*-"$HOST" 2>/dev/null | head -1) || true
	[ -n "$dir" ] || return 1
	echo "$dir/bin"
}

# ---- toolchain -------------------------------------------------------------
if ! toolchain_bin >/dev/null 2>&1; then
	echo "== downloading LLVM-MinGW ($LLVM_MINGW) ..."
	URL="https://github.com/mstorsjo/llvm-mingw/releases/download/${LLVM_MINGW}/llvm-mingw-${LLVM_MINGW}-ucrt-ubuntu-22.04-${HOST}.tar.xz"
	curl -sSL -o toolchain.tar.xz "$URL"
	tar -xf toolchain.tar.xz
fi
BIN="$(toolchain_bin)"

# ---- OBS headers + runtime -------------------------------------------------
[ -d "$WORK/obs-src" ] || {
	echo "== downloading OBS $OBS_VERSION sources ..."
	curl -sSL -o obs-src.zip "https://github.com/obsproject/obs-studio/archive/refs/tags/$OBS_VERSION.zip"
	unzip -q -o obs-src.zip -d "$WORK/obs-src"
}
OBS_INC="$WORK/obs-src/obs-studio-$OBS_VERSION/libobs"

[ -f "$WORK/obs.dll" ] || {
	echo "== downloading the OBS $OBS_VERSION runtime (for libobs) ..."
	curl -sSL -o obs-rt.zip "https://github.com/obsproject/obs-studio/releases/download/$OBS_VERSION/OBS-Studio-$OBS_VERSION-Windows-x64.zip"
	unzip -q -o obs-rt.zip 'bin/64bit/obs.dll' 'bin/64bit/obs-frontend-api.dll' -d "$WORK/obs-rt"
	cp -f "$WORK/obs-rt/bin/64bit/obs.dll" "$WORK/obs.dll"
	cp -f "$WORK/obs-rt/bin/64bit/obs-frontend-api.dll" "$WORK/obs-frontend-api.dll"
}

# obsconfig.h is generated by the OBS build; a minimal one is enough here.
cat > "$OBS_INC/obsconfig.h" <<'EOF'
#pragma once

#define OBS_DATA_PATH "data"
#define OBS_PLUGIN_PATH "obs-plugins/64bit"
#define OBS_PLUGIN_DESTINATION "obs-plugins/64bit"

#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
EOF

# ---- libobs import library -------------------------------------------------
if [ ! -f "$WORK/libobs.a" ]; then
	echo "== generating libobs.a from obs.dll exports ..."
	"$BIN/llvm-objdump" -p "$WORK/obs.dll" |
		awk '/^Export Table:/{f=1} f && /^[[:space:]]+[0-9]+[[:space:]]+0x[0-9a-f]+[[:space:]]+[A-Za-z_]/{print $3}' \
		> "$WORK/exports.txt"
	[ "$(wc -l < "$WORK/exports.txt")" -gt 500 ] || { echo "unexpected export list"; exit 1; }
	{ echo "LIBRARY obs.dll"; echo "EXPORTS"; cat "$WORK/exports.txt"; } > "$WORK/obs.def"
	"$BIN/llvm-dlltool" -m i386:x86-64 -d "$WORK/obs.def" -l "$WORK/libobs.a"
fi

# ---- obs-frontend-api import library --------------------------------------
if [ ! -f "$WORK/libobs-frontend-api.a" ]; then
	echo "== generating libobs-frontend-api.a from obs-frontend-api.dll exports ..."
	"$BIN/llvm-objdump" -p "$WORK/obs-frontend-api.dll" |
		awk '/^Export Table:/{f=1} f && /^[[:space:]]+[0-9]+[[:space:]]+0x[0-9a-f]+[[:space:]]+[A-Za-z_]/{print $3}' \
		> "$WORK/frontend-exports.txt"
	[ "$(wc -l < "$WORK/frontend-exports.txt")" -gt 20 ] || { echo "unexpected frontend export list"; exit 1; }
	{ echo "LIBRARY obs-frontend-api.dll"; echo "EXPORTS"; cat "$WORK/frontend-exports.txt"; } > "$WORK/obs-frontend-api.def"
	"$BIN/llvm-dlltool" -m i386:x86-64 -d "$WORK/obs-frontend-api.def" -l "$WORK/libobs-frontend-api.a"
fi

# The module entry points must be exported explicitly (PE has no visibility).
cat > "$WORK/topscreen.def" <<'EOF'
LIBRARY topscreen
EXPORTS
    obs_module_load
    obs_module_unload
    obs_module_ver
    obs_module_set_pointer
    obs_module_description
EOF

# ---- compile ---------------------------------------------------------------
SRCS=$(cd "$ROOT" && python3 - <<'PY'
import re
from pathlib import Path
s = Path('CMakeLists.txt').read_text()
plugin = [l.strip() for l in re.search(r'set\(TOPSCREEN_SOURCES(.*?)\)', s, re.S).group(1).splitlines() if l.strip().endswith('.cpp')]
core = [l.strip() for l in re.search(r'set\(TOPSCREEN_CORE_SOURCES(.*?)\)', s, re.S).group(1).splitlines() if l.strip().endswith('.cpp')]
print(' '.join(f for f in plugin + core if 'ts-dock' not in f and '${' not in f))
PY
)

echo "== compiling ($(echo "$SRCS" | wc -w) files, no Qt dock) ..."
cd "$ROOT" # sources are relative to the repository
# shellcheck disable=SC2086
"$BIN/x86_64-w64-mingw32-clang++" -std=c++20 -O2 -shared \
	-static-libstdc++ \
	-DTOPSCREEN_VERSION="\"$VER\"" \
	-I "$ROOT/src" -I "$ROOT/third_party" -I "$OBS_INC" \
	-I "$WORK/obs-src/obs-studio-$OBS_VERSION/frontend/api" \
	$SRCS "$WORK/libobs.a" "$WORK/libobs-frontend-api.a" "$WORK/topscreen.def" \
	-Wl,-Bstatic -lunwind -Wl,-Bdynamic \
	-lwinmm -luser32 \
	-o "$ROOT/build/topscreen.dll"

echo "OK: $ROOT/build/topscreen.dll"
echo "Next: scripts/package.sh   # writes releases/topscreen-$VER-windows.zip"
