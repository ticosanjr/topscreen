#!/usr/bin/env bash
#
# COMPILE check of the plugin against the REAL OBS headers, without needing
# libobs installed (uses -fsyntax-only, does not link).
#
# Catches API/signature/type/field-order errors that the core tests do not
# catch. Also runs in CI (see .github/workflows/check-obs-headers.yml).
#
# The dock (src/ui) is checked with real Qt6 when available; otherwise it uses
# the minimal stub in tools/qt-stub.
#
# Usage:
#   tools/check-obs-headers.sh
#
# Variables:
#   OBS_REF             OBS reference (default: the obs-studio version in buildspec.json)
#   TOPSCREEN_CHECK_DIR working/cache directory (default: $TMPDIR/topscreen-obscheck)
#   CXX                 compiler (default: g++)
#
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${TOPSCREEN_CHECK_DIR:-${TMPDIR:-/tmp}/topscreen-obscheck}"
DEFAULT_OBS_REF="$(
    sed -n '/"obs-studio"/,/}/p' "$ROOT/buildspec.json" |
        sed -n 's/.*"version": "\([^"]*\)".*/\1/p' | head -1
)"
OBS_REF="${OBS_REF:-${DEFAULT_OBS_REF:-master}}"
CXX="${CXX:-g++}"
QT_STUB="$ROOT/tools/qt-stub"

mkdir -p "$WORK"
OBS="$WORK/obs-src"
SIMDE="$WORK/simde-src"
STUB="$WORK/stub"

if [ ! -d "$OBS/libobs" ]; then
    echo "Downloading OBS headers ($OBS_REF) to $WORK ..."
    mkdir -p "$WORK/unpack"
    if ! curl -fsSL --retry 3 -o "$WORK/obs.tar.gz" \
        "https://github.com/obsproject/obs-studio/archive/refs/tags/${OBS_REF}.tar.gz"; then
        curl -fsSL --retry 3 -o "$WORK/obs.tar.gz" \
            "https://github.com/obsproject/obs-studio/archive/refs/heads/${OBS_REF}.tar.gz"
    fi
    tar xzf "$WORK/obs.tar.gz" -C "$WORK/unpack"
    mv "$WORK/unpack/obs-studio-${OBS_REF}" "$OBS"
fi

if [ ! -d "$SIMDE/simde" ]; then
    echo "Downloading simde (OBS SIMD) ..."
    curl -fsSL --retry 3 -o "$WORK/simde.tar.gz" \
        "https://github.com/simd-everywhere/simde/archive/refs/heads/master.tar.gz"
    tar xzf "$WORK/simde.tar.gz" -C "$WORK"
    mv "$WORK/simde-master" "$SIMDE"
fi

# Header generated by the OBS CMake (stub sufficient for the check).
mkdir -p "$STUB"
cat > "$STUB/obsconfig.h" <<'EOF'
#pragma once
#define OBS_DATA_PATH "/tmp"
#define OBS_PLUGIN_PATH "/tmp"
#define OBS_PLUGIN_DESTINATION "obs-plugins"
#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
EOF

BASE_INC=(-I"$ROOT/src" -I"$ROOT/third_party" -I"$STUB" -I"$OBS/libobs" -I"$SIMDE"
	-I"$OBS/frontend/api" -I"$OBS/UI/obs-frontend-api")
DEF=(-DTOPSCREEN_VERSION='"0.0.0-check"')

if [ -f /usr/include/X11/Xlib.h ]; then
    DEF+=(-DTOPSCREEN_HAVE_X11)
    echo "X11 detected: X11 backend included in the check."
else
    echo "X11 missing: X11 backend will NOT be checked."
fi

if [ -f /usr/include/X11/extensions/XShm.h ]; then
    DEF+=(-DTOPSCREEN_HAVE_XSHM)
    echo "XShm detected: native capture backend included in the check."
fi

if [ -f /usr/include/linux/input.h ]; then
    DEF+=(-DTOPSCREEN_HAVE_EVDEV)
    echo "linux/input.h detected: evdev backend included in the check."
fi

# Qt (real if available, otherwise stub) to check the dock.
QT_INC=()
if pkg-config --exists Qt6Widgets 2>/dev/null; then
    # shellcheck disable=SC2207
    QT_INC=($(pkg-config --cflags Qt6Widgets))
    DEF+=(-DTOPSCREEN_HAVE_QT)
    echo "Qt6 detected: dock will be checked with real Qt."
elif [ -d "$QT_STUB" ]; then
    QT_INC=(-I"$QT_STUB")
    DEF+=(-DTOPSCREEN_HAVE_QT)
    echo "Qt6 missing: dock will be checked with the stub (tools/qt-stub)."
else
    echo "Qt missing and no stub: dock will NOT be checked."
fi

cd "$ROOT" || exit 2

fail=0
count=0
while IFS= read -r f; do
    case "$f" in
    src/ui/*)
        if [ "${#QT_INC[@]}" -eq 0 ]; then
            continue
        fi
        ;;
    esac
    count=$((count + 1))
    # -Wno-missing-field-initializers: OBS structs are initialized by
    # designated initializers, leaving optional fields out (intentional).
    if "$CXX" -std=c++20 -fsyntax-only -Wall -Wextra -Wno-missing-field-initializers \
        "${BASE_INC[@]}" "${QT_INC[@]}" "${DEF[@]}" "$f"; then
        echo "OK   $f"
    else
        echo "FAIL $f"
        fail=1
    fi
done < <(find src -name '*.cpp' | sort)

echo
if [ "$fail" -eq 0 ]; then
    echo "Check OK: $count files compile against the OBS/Qt headers."
else
    echo "Check FAILED."
fi
exit "$fail"
